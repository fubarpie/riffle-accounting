-- 0006_reconciliation.sql
-- Phase 4: account reconciliation and the statement vault.
-- See docs/adr/0010-reconciliation-and-vault.md.
--
-- A reconciliation clears journal lines of one asset/liability account against
-- a bank or card statement. It never touches the ledger itself: posted lines
-- stay append-only (ADR 0004). Items are working state while the reconciliation
-- is a draft and become frozen when it is completed.

CREATE TYPE reconciliation_status AS ENUM ('draft', 'completed', 'voided');

-- ------------------------------------------------------- reconciliations
CREATE TABLE reconciliations (
  id                    uuid PRIMARY KEY,
  business_id           uuid NOT NULL REFERENCES businesses (id),
  account_id            uuid NOT NULL,
  statement_start       date NOT NULL,
  statement_end         date NOT NULL,
  -- Statement balances in signed minor units as the statement prints them
  -- (a credit card owing money is positive; see ADR 0010 for the sign rule).
  opening_balance_minor bigint NOT NULL,
  closing_balance_minor bigint NOT NULL,
  status                reconciliation_status NOT NULL DEFAULT 'draft',
  completed_at          timestamptz,
  completed_by          uuid REFERENCES users (id),
  voided_at             timestamptz,
  voided_by             uuid REFERENCES users (id),
  created_by            uuid NOT NULL REFERENCES users (id),
  created_at            timestamptz NOT NULL DEFAULT now(),
  updated_at            timestamptz NOT NULL DEFAULT now(),
  UNIQUE (business_id, id),
  FOREIGN KEY (business_id, account_id) REFERENCES accounts (business_id, id),
  CHECK (statement_end >= statement_start),
  CHECK ((completed_at IS NULL) = (completed_by IS NULL)),
  CHECK ((voided_at IS NULL) = (voided_by IS NULL)),
  CHECK ((status = 'voided') = (voided_at IS NOT NULL)),
  CHECK (status <> 'completed' OR completed_at IS NOT NULL),
  CHECK (status <> 'draft' OR completed_at IS NULL)
);
CREATE INDEX reconciliations_account_idx ON reconciliations (business_id, account_id, statement_end DESC);
-- One open draft per account, and one completed reconciliation per statement end.
CREATE UNIQUE INDEX reconciliations_one_draft_uniq
  ON reconciliations (business_id, account_id) WHERE status = 'draft';
CREATE UNIQUE INDEX reconciliations_completed_end_uniq
  ON reconciliations (business_id, account_id, statement_end) WHERE status = 'completed';

-- --------------------------------------------------- reconciliation_items
CREATE TABLE reconciliation_items (
  id                uuid PRIMARY KEY,
  business_id       uuid NOT NULL REFERENCES businesses (id),
  reconciliation_id uuid NOT NULL,
  line_id           uuid NOT NULL,
  created_by        uuid NOT NULL REFERENCES users (id),
  created_at        timestamptz NOT NULL DEFAULT now(),
  -- Set when the parent is voided: the row stays as history but releases the line.
  voided_at         timestamptz,
  UNIQUE (business_id, id),
  UNIQUE (business_id, reconciliation_id, line_id),
  FOREIGN KEY (business_id, reconciliation_id) REFERENCES reconciliations (business_id, id),
  FOREIGN KEY (business_id, line_id)           REFERENCES journal_lines (business_id, id)
);
CREATE INDEX reconciliation_items_recon_idx ON reconciliation_items (business_id, reconciliation_id);
-- A line may be cleared by at most one non-voided reconciliation.
CREATE UNIQUE INDEX reconciliation_items_active_line_uniq
  ON reconciliation_items (business_id, line_id) WHERE voided_at IS NULL;

-- ------------------------------------------------------ statement_documents
CREATE TABLE statement_documents (
  id                uuid PRIMARY KEY,
  business_id       uuid NOT NULL REFERENCES businesses (id),
  reconciliation_id uuid,
  -- Display name only (sanitised). Never used to build a filesystem path.
  filename          text NOT NULL CHECK (length(filename) BETWEEN 1 AND 255),
  -- Detected from the file's bytes, not taken from the client.
  content_type      text NOT NULL CHECK (content_type IN ('application/pdf', 'image/png', 'image/jpeg', 'text/csv')),
  size_bytes        bigint NOT NULL CHECK (size_bytes > 0),
  sha256            char(64) NOT NULL CHECK (sha256 ~ '^[0-9a-f]{64}$'),
  -- <business uuid>/<document uuid>, generated by the server.
  storage_key       text NOT NULL UNIQUE
    CHECK (storage_key ~ '^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}/[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$'),
  uploaded_by       uuid NOT NULL REFERENCES users (id),
  created_at        timestamptz NOT NULL DEFAULT now(),
  UNIQUE (business_id, id),
  FOREIGN KEY (business_id, reconciliation_id) REFERENCES reconciliations (business_id, id)
);
CREATE INDEX statement_documents_recon_idx ON statement_documents (business_id, reconciliation_id);

-- --------------------------------------------------------------- guards
-- Reconciliation rows: the statement facts never change; status moves
-- draft -> completed | voided and completed -> voided only.
CREATE FUNCTION reconciliations_guard() RETURNS trigger
  LANGUAGE plpgsql AS $$
DECLARE
  acct_type account_type;
BEGIN
  IF TG_OP = 'DELETE' THEN
    RAISE EXCEPTION 'reconciliations cannot be deleted; void them' USING ERRCODE = '55000';
  END IF;
  IF TG_OP = 'INSERT' THEN
    SELECT type INTO acct_type FROM accounts WHERE business_id = NEW.business_id AND id = NEW.account_id;
    IF acct_type IS NULL OR acct_type NOT IN ('asset', 'liability') THEN
      RAISE EXCEPTION 'only asset and liability accounts can be reconciled' USING ERRCODE = '23514';
    END IF;
    IF NEW.status <> 'draft' THEN
      RAISE EXCEPTION 'a reconciliation starts as a draft' USING ERRCODE = '23514';
    END IF;
    RETURN NEW;
  END IF;
  -- UPDATE
  IF NEW.business_id <> OLD.business_id OR NEW.account_id <> OLD.account_id
     OR NEW.statement_start <> OLD.statement_start OR NEW.statement_end <> OLD.statement_end
     OR NEW.opening_balance_minor <> OLD.opening_balance_minor
     OR NEW.closing_balance_minor <> OLD.closing_balance_minor
     OR NEW.created_by <> OLD.created_by OR NEW.created_at <> OLD.created_at THEN
    RAISE EXCEPTION 'reconciliation statement facts are immutable' USING ERRCODE = '55000';
  END IF;
  IF OLD.status = 'voided' THEN
    RAISE EXCEPTION 'voided reconciliations are immutable' USING ERRCODE = '55000';
  END IF;
  IF OLD.status = 'completed' AND NEW.status <> 'voided' THEN
    RAISE EXCEPTION 'a completed reconciliation can only be voided' USING ERRCODE = '55000';
  END IF;
  IF OLD.status = 'completed' AND (NEW.completed_at IS DISTINCT FROM OLD.completed_at
     OR NEW.completed_by IS DISTINCT FROM OLD.completed_by) THEN
    RAISE EXCEPTION 'completion details are immutable' USING ERRCODE = '55000';
  END IF;
  IF OLD.status = 'draft' AND NEW.status = 'draft' AND NEW.completed_at IS NOT NULL THEN
    RAISE EXCEPTION 'a draft cannot carry completion details' USING ERRCODE = '55000';
  END IF;
  RETURN NEW;
END
$$;
CREATE TRIGGER reconciliations_guard BEFORE INSERT OR UPDATE OR DELETE ON reconciliations
  FOR EACH ROW EXECUTE FUNCTION reconciliations_guard();

-- Items: add/remove only while the parent is a draft; once the parent is
-- completed they are frozen; voiding the parent may only stamp voided_at.
CREATE FUNCTION reconciliation_items_guard() RETURNS trigger
  LANGUAGE plpgsql AS $$
DECLARE
  parent_status reconciliation_status;
  parent_account uuid;
  line_account uuid;
BEGIN
  IF TG_OP = 'DELETE' THEN
    SELECT status INTO parent_status FROM reconciliations
      WHERE business_id = OLD.business_id AND id = OLD.reconciliation_id;
    IF parent_status IS DISTINCT FROM 'draft' THEN
      RAISE EXCEPTION 'items of a % reconciliation cannot be removed', coalesce(parent_status::text, 'missing')
        USING ERRCODE = '55000';
    END IF;
    RETURN OLD;
  END IF;

  IF TG_OP = 'UPDATE' THEN
    SELECT status INTO parent_status FROM reconciliations
      WHERE business_id = OLD.business_id AND id = OLD.reconciliation_id;
    IF NEW.id <> OLD.id OR NEW.business_id <> OLD.business_id
       OR NEW.reconciliation_id <> OLD.reconciliation_id OR NEW.line_id <> OLD.line_id
       OR NEW.created_by <> OLD.created_by OR NEW.created_at <> OLD.created_at
       OR OLD.voided_at IS NOT NULL OR NEW.voided_at IS NULL
       OR parent_status IS DISTINCT FROM 'voided' THEN
      RAISE EXCEPTION 'reconciliation items are immutable; only voiding the parent releases them'
        USING ERRCODE = '55000';
    END IF;
    RETURN NEW;
  END IF;

  -- INSERT
  SELECT status, account_id INTO parent_status, parent_account FROM reconciliations
    WHERE business_id = NEW.business_id AND id = NEW.reconciliation_id;
  IF parent_status IS DISTINCT FROM 'draft' THEN
    RAISE EXCEPTION 'lines can only be cleared in a draft reconciliation' USING ERRCODE = '55000';
  END IF;
  SELECT account_id INTO line_account FROM journal_lines
    WHERE business_id = NEW.business_id AND id = NEW.line_id;
  IF line_account IS DISTINCT FROM parent_account THEN
    RAISE EXCEPTION 'line belongs to a different account than the reconciliation' USING ERRCODE = '23514';
  END IF;
  IF NEW.voided_at IS NOT NULL THEN
    RAISE EXCEPTION 'new items cannot be created voided' USING ERRCODE = '23514';
  END IF;
  RETURN NEW;
END
$$;
CREATE TRIGGER reconciliation_items_guard BEFORE INSERT OR UPDATE OR DELETE ON reconciliation_items
  FOR EACH ROW EXECUTE FUNCTION reconciliation_items_guard();

-- Documents: attach to a draft or completed reconciliation; deletable only
-- while unattached or attached to a draft. Content never changes (no UPDATE grant).
CREATE FUNCTION statement_documents_guard() RETURNS trigger
  LANGUAGE plpgsql AS $$
DECLARE
  parent_status reconciliation_status;
BEGIN
  IF TG_OP = 'INSERT' THEN
    IF NEW.reconciliation_id IS NOT NULL THEN
      SELECT status INTO parent_status FROM reconciliations
        WHERE business_id = NEW.business_id AND id = NEW.reconciliation_id;
      IF parent_status IS NULL OR parent_status = 'voided' THEN
        RAISE EXCEPTION 'statements cannot be attached to a voided reconciliation' USING ERRCODE = '55000';
      END IF;
    END IF;
    RETURN NEW;
  END IF;
  -- DELETE
  IF OLD.reconciliation_id IS NOT NULL THEN
    SELECT status INTO parent_status FROM reconciliations
      WHERE business_id = OLD.business_id AND id = OLD.reconciliation_id;
    IF parent_status IS DISTINCT FROM 'draft' THEN
      RAISE EXCEPTION 'statements can only be deleted while the reconciliation is a draft'
        USING ERRCODE = '55000';
    END IF;
  END IF;
  RETURN OLD;
END
$$;
CREATE TRIGGER statement_documents_guard BEFORE INSERT OR DELETE ON statement_documents
  FOR EACH ROW EXECUTE FUNCTION statement_documents_guard();

CREATE TRIGGER reconciliations_no_truncate BEFORE TRUNCATE ON reconciliations
  FOR EACH STATEMENT EXECUTE FUNCTION reject_mutation();
CREATE TRIGGER reconciliation_items_no_truncate BEFORE TRUNCATE ON reconciliation_items
  FOR EACH STATEMENT EXECUTE FUNCTION reject_mutation();
CREATE TRIGGER statement_documents_no_truncate BEFORE TRUNCATE ON statement_documents
  FOR EACH STATEMENT EXECUTE FUNCTION reject_mutation();

-- A line that a completed reconciliation has cleared cannot be reversed
-- (edited or voided) any more: that would silently change a reconciled balance.
-- Void the reconciliation first. Reversals are the only way posted lines change.
CREATE FUNCTION check_reversal_not_reconciled() RETURNS trigger
  LANGUAGE plpgsql AS $$
BEGIN
  IF NEW.reverses_entry_id IS NOT NULL AND EXISTS (
    SELECT 1
      FROM journal_lines l
      JOIN reconciliation_items i ON i.business_id = l.business_id AND i.line_id = l.id AND i.voided_at IS NULL
      JOIN reconciliations r ON r.business_id = i.business_id AND r.id = i.reconciliation_id
     WHERE l.business_id = NEW.business_id AND l.entry_id = NEW.reverses_entry_id
       AND r.status = 'completed'
  ) THEN
    RAISE EXCEPTION 'transaction has lines cleared by a completed reconciliation; void the reconciliation first'
      USING ERRCODE = '55000';
  END IF;
  RETURN NEW;
END
$$;
CREATE TRIGGER journal_entries_reconciled_guard BEFORE INSERT ON journal_entries
  FOR EACH ROW EXECUTE FUNCTION check_reversal_not_reconciled();

-- ------------------------------------------------------------------ RLS
-- Same pattern as every other tenant table: enabled AND forced, one policy on app.business_id.
DO $$
DECLARE
  t text;
BEGIN
  FOREACH t IN ARRAY ARRAY['reconciliations','reconciliation_items','statement_documents']
  LOOP
    EXECUTE format('ALTER TABLE %I ENABLE ROW LEVEL SECURITY', t);
    EXECUTE format('ALTER TABLE %I FORCE ROW LEVEL SECURITY', t);
    EXECUTE format(
      'CREATE POLICY tenant_isolation ON %I FOR ALL TO riffle_app
         USING (business_id = app_business_id())
         WITH CHECK (business_id = app_business_id())', t);
  END LOOP;
END
$$;

-- ---------------------------------------------------------------- audit
-- As in 0003/0004, audit rows are written by the application in the same
-- transaction (reconciliation.create / .items / .complete / .void,
-- statement.upload / .delete). audit_log ids are UUIDv7 minted in the app, so
-- a trigger is deliberately not used.

-- --------------------------------------------------------------- grants
-- No DELETE on reconciliations. Items may be deleted (the trigger limits that
-- to drafts); documents may be deleted (trigger: unattached or draft only).
GRANT SELECT, INSERT, UPDATE ON reconciliations TO riffle_app;
GRANT SELECT, INSERT, UPDATE, DELETE ON reconciliation_items TO riffle_app;
GRANT SELECT, INSERT, DELETE ON statement_documents TO riffle_app;
